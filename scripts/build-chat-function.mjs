// Writes api/_lib/assistant.js and api/_lib/copilot.mjs: the assistant logic (packages/data/src/assistant.ts) as plain CommonJS.
// The Vercel function api/chat.js requires this file, so it runs like the working json-server function (plain JavaScript,
// no TypeScript build, no workspace packages). Run `pnpm build:chat` after changing assistant.ts; a test fails when the copy is stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const source = join(root, 'packages', 'data', 'src', 'assistant.ts')
export const target = join(root, 'api', '_lib', 'assistant.js')

// esbuild comes with tsx (already a dev dependency), so this adds no package. TypeScript 7 has no transpile API of its own.
const esbuild = createRequire(createRequire(import.meta.url).resolve('tsx/package.json'))('esbuild')

export function transpile() {
  const out = esbuild.transformSync(readFileSync(source, 'utf8'), { loader: 'ts', format: 'cjs', target: 'es2022' }).code
  return `// GENERATED by scripts/build-chat-function.mjs from packages/data/src/assistant.ts. Do not edit; run \`pnpm build:chat\`.\n${out}`
}

// The CopilotKit runtime (server/copilot.ts) as one ES module (.mjs). Packages stay external and are loaded with import, so Node never has to require() an ES-only dependency.
export const copilotSource = join(root, 'server', 'copilot.ts')
export const copilotTarget = join(root, 'api', '_lib', 'copilot.mjs')

export function bundleCopilot() {
  const out = esbuild.buildSync({
    entryPoints: [copilotSource], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node22',
    external: ['@copilotkit/*', 'zod'], logLevel: 'silent',
  }).outputFiles[0].text
  return `// GENERATED by scripts/build-chat-function.mjs from server/copilot.ts. Do not edit; run \`pnpm build:chat\`.\n${out}`
}

// Live ingestion for the hosted site (ingest/hosted.ts and what it uses) as one ES module. @vercel/blob stays external and is loaded when first needed.
export const ingestSource = join(root, 'ingest', 'hosted.ts')
export const ingestTarget = join(root, 'api', '_lib', 'ingest.mjs')

export function bundleIngest() {
  const out = esbuild.buildSync({
    entryPoints: [ingestSource], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node22',
    external: ['@vercel/blob'], logLevel: 'silent',
  }).outputFiles[0].text
  return `// GENERATED by scripts/build-chat-function.mjs from ingest/hosted.ts. Do not edit; run \`pnpm build:chat\`.\n${out}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, transpile())
  console.log(`Wrote ${target}`)
  writeFileSync(copilotTarget, bundleCopilot())
  console.log(`Wrote ${copilotTarget}`)
  writeFileSync(ingestTarget, bundleIngest())
  console.log(`Wrote ${ingestTarget}`)
}
