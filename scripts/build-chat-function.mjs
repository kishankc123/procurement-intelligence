// Writes api/_lib/assistant.js: the assistant logic (packages/data/src/assistant.ts) as plain CommonJS.
// The Vercel function api/chat.js requires this file, so it runs like the working json-server function (plain JavaScript,
// no TypeScript build, no workspace packages). Run `pnpm build:chat` after changing assistant.ts; a test fails when the copy is stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const source = join(root, 'packages', 'data', 'src', 'assistant.ts')
export const target = join(root, 'api', '_lib', 'assistant.js')

// esbuild comes with tsx (already a dev dependency), so this adds no package. TypeScript 7 has no transpile API of its own.
const esbuild = createRequire(createRequire(import.meta.url).resolve('tsx/package.json'))('esbuild')

export function transpile() {
  const out = esbuild.transformSync(readFileSync(source, 'utf8'), { loader: 'ts', format: 'cjs', target: 'es2022' }).code
  return `// GENERATED by scripts/build-chat-function.mjs from packages/data/src/assistant.ts. Do not edit; run \`pnpm build:chat\`.\n${out}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, transpile())
  console.log(`Wrote ${target}`)
}
